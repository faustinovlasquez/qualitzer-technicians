const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { spawnSync } = require("node:child_process");
const { pathToFileURL } = require("node:url");
const ts = require("typescript");
const root = path.resolve(__dirname, "../..");
process.chdir(root);
const output = fs.mkdtempSync(path.join(os.tmpdir(), "qualitzer-login-validation-"));
const targets = ["src/screens/LoginScreen.tsx", "App.tsx", "tests/login-user-ui.test.ts"];
const config = ts.readConfigFile(path.join(root, "tsconfig.json"), ts.sys.readFile);
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
const program = ts.createProgram(targets.map((name) => path.join(root, name)), { ...parsed.options, types: ["node", "react"] });
const owned = new Set(targets.map((name) => path.resolve(root, name).toLowerCase()));
const diagnostics = ts.getPreEmitDiagnostics(program).filter((item) => !item.file || owned.has(path.resolve(item.file.fileName).toLowerCase())).map((item) => ({ file: item.file?.fileName, code: item.code, message: ts.flattenDiagnosticMessageText(item.messageText, "\n") }));
const tests = ["tests/login-user-ui.test.ts", "tests/gateway-connection.test.ts", "tests/standalone-gateway.test.ts", "tests/standalone-session.test.ts"];
const unit = spawnSync(process.execPath, ["--import", pathToFileURL(require.resolve("tsx")).href, "--test", ...tests], { cwd: root, encoding: "utf8" });
fs.writeFileSync(path.join(output, "tests.log"), `${unit.stdout ?? ""}\n${unit.stderr ?? ""}`);
const ui = spawnSync(process.execPath, ["tests/e2e/login-user-smoke.cjs"], { cwd: root, encoding: "utf8" });
fs.writeFileSync(path.join(output, "ui.log"), `${ui.stdout ?? ""}\n${ui.stderr ?? ""}`);
const report = { date: new Date().toISOString(), output, targets, diagnostics, tests, testExit: unit.status, uiExit: ui.status, uiReport: ui.stdout?.trim(), passed: diagnostics.length === 0 && unit.status === 0 && ui.status === 0 };
fs.writeFileSync(path.join(output, "validation.json"), JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
if (!report.passed) process.exitCode = 1;